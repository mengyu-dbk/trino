    CAST('1' AS UINT256),
    CAST('1' AS UINT256),
    CAST('100' AS UINT256),
    CAST('100' AS UINT256),
    CAST('1000' AS UINT256),
    CAST('115792089237316195423570985008687907853269984665640564039457584007913129639935' AS UINT256),
    CAST('115792089237316195423570985008687907853269984665640564039457584007913129639935' AS UINT256)
) t(x);

