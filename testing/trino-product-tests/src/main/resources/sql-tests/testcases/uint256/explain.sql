-- database: trino; groups: uint256;
CREATE SCHEMA IF NOT EXISTS iceberg.default;

DROP TABLE IF EXISTS iceberg.default.uint256_explain_test;

CREATE TABLE iceberg.default.uint256_explain_test AS
SELECT * FROM (VALUES
    (CAST('1' AS UINT256), CAST('100' AS UINT256)),
    (CAST('2' AS UINT256), CAST('200' AS UINT256)),
    (CAST('3' AS UINT256), CAST('300' AS UINT256)),
    (CAST('4' AS UINT256), CAST('100000000000000000000000000000000000000' AS UINT256)),
    (CAST('5' AS UINT256), CAST('115792089237316195423570985008687907853269984665640564039457584007913129639935' AS UINT256))
) t(id, value);

EXPLAIN (TYPE LOGICAL)
SELECT id, value
FROM iceberg.default.uint256_explain_test
WHERE value > CAST('1000' AS UINT256);